"""Shared enumerations for the DroneFleet Commander backend."""
from enum import Enum


class FlightMode(str, Enum):
    IDLE = "IDLE"
    TAKEOFF = "TAKEOFF"
    AUTONOMOUS = "AUTONOMOUS"
    MANUAL = "MANUAL"
    PAUSED = "PAUSED"
    REJOINING = "REJOINING"
    RETURN_TO_HOME = "RETURN_TO_HOME"
    LANDING = "LANDING"
    EMERGENCY = "EMERGENCY"


class DroneStatus(str, Enum):
    READY = "READY"
    ON_MISSION = "ON_MISSION"
    RETURNING = "RETURNING"
    CHARGING = "CHARGING"
    FAILED = "FAILED"
    OFFLINE = "OFFLINE"


class MissionStatus(str, Enum):
    CREATED = "CREATED"
    PLANNING = "PLANNING"
    READY = "READY"
    ACTIVE = "ACTIVE"
    PAUSED = "PAUSED"
    REPLANNING = "REPLANNING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    ABORTED = "ABORTED"


class WaypointAction(str, Enum):
    TRANSIT = "TRANSIT"
    INSPECT = "INSPECT"
    HOVER = "HOVER"
    LAND = "LAND"


class Capability(str, Enum):
    CAMERA = "CAMERA"
    THERMAL = "THERMAL"
    LIDAR = "LIDAR"
    HEAVY_LIFT = "HEAVY_LIFT"


class ZoneKind(str, Enum):
    RESTRICTED = "RESTRICTED"     # no-fly, blocks planning
    OBSTACLE = "OBSTACLE"         # physical obstacle, blocks planning
    WEATHER = "WEATHER"           # passable but costly (risk multiplier)
    INSPECTION = "INSPECTION"     # mission target area, does not block


class EventType(str, Enum):
    MISSION_CREATED = "MISSION_CREATED"
    MISSION_STARTED = "MISSION_STARTED"
    MISSION_COMPLETED = "MISSION_COMPLETED"
    MISSION_FAILED = "MISSION_FAILED"
    MISSION_REASSIGNED = "MISSION_REASSIGNED"
    DRONE_ASSIGNED = "DRONE_ASSIGNED"
    ROUTE_GENERATED = "ROUTE_GENERATED"
    ROUTE_REPLANNED = "ROUTE_REPLANNED"
    WAYPOINT_REACHED = "WAYPOINT_REACHED"
    ROUTE_COMPLETED = "ROUTE_COMPLETED"
    TAKEOFF_COMPLETED = "TAKEOFF_COMPLETED"
    LANDED = "LANDED"
    CONTROL_TAKEOVER = "CONTROL_TAKEOVER"
    CONTROL_RELEASED = "CONTROL_RELEASED"
    MODE_CHANGED = "MODE_CHANGED"
    ROUTE_REJOIN_STARTED = "ROUTE_REJOIN_STARTED"
    ROUTE_REJOIN_COMPLETED = "ROUTE_REJOIN_COMPLETED"
    RETURN_HOME_STARTED = "RETURN_HOME_STARTED"
    RETURN_HOME_COMPLETED = "RETURN_HOME_COMPLETED"
    FAILURE_DETECTED = "FAILURE_DETECTED"
    ANOMALY_DETECTED = "ANOMALY_DETECTED"
    BATTERY_WARNING = "BATTERY_WARNING"
    AI_DECISION = "AI_DECISION"
    COMMAND_REJECTED = "COMMAND_REJECTED"
    INJECTED_EVENT = "INJECTED_EVENT"
    INFO = "INFO"
